const norm = (s: string) => s.replace(/\s+/g, " ").trim();
const INDEX = new Map(Object.entries(EN).map(([k, v]) => [norm(k), v]));

/** Câu dịch tiếng Anh của một câu hát, hoặc undefined nếu chưa có */
export function translateLine(text: string): string | undefined {
  return INDEX.get(norm(text));
}

/** Bài này có lời dịch không (để chỉ hiện nút «Lời dịch» khi có) */
export function hasTranslation(lines: { words: { text: string }[] }[]): boolean {
  return lines.some((l) => INDEX.has(norm(l.words.map((w) => w.text).join(" "))));
}
